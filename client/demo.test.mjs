// Run: node client/demo.test.mjs   (Node 18+)
import { createDemoClient } from './demo.js';
import { Conflict } from './ghstore.js';

const store = new Map();
globalThis.localStorage = { getItem: (k) => store.get(k) ?? null, setItem: (k, v) => store.set(k, String(v)), removeItem: (k) => store.delete(k) };
globalThis.location = { reload() {} };

let fails = 0;
const check = (n, ok) => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${n}`); if (!ok) fails++; };

const gh = createDemoClient({ folder: 'app', seed: { 'seed.txt': 'planted', 'dir/x.md': 'x' } });
check('starts signed out', !(await gh.signedIn()) && (await gh.token()) === null);
await gh.signIn();
check('signIn signs in', (await gh.signedIn()) && (await gh.login()) === 'demo-user');
const [repo] = await gh.repos();
check('one demo repo', repo.full === 'demo/my-data');
check('seed files appear on first sign-in', (await gh.read(repo.full, 'seed.txt'))?.text === 'planted' && (await gh.list(repo.full, '')).some((x) => x.name === 'dir'));
check('missing file is null', (await gh.read(repo.full, 'a.txt')) === null);
const s1 = await gh.write(repo.full, 'a.txt', 'one');
const f = await gh.read(repo.full, 'a.txt');
check('write then read', f.text === 'one' && f.sha === s1 && f.etag === `"${s1}"`);
check('etag gives notModified', (await gh.read(repo.full, 'a.txt', undefined, f.etag)).notModified === true);
await gh.write(repo.full, 'a.txt', 'two').then(() => check('creating over an existing file conflicts', false), (e) => check('creating over an existing file conflicts', e instanceof Conflict));
const s2 = await gh.write(repo.full, 'a.txt', 'two', s1);
await gh.write(repo.full, 'a.txt', 'x', s1).then(() => check('stale sha conflicts', false), (e) => check('stale sha conflicts', e instanceof Conflict));
await gh.write(repo.full, 'sub/b.txt', 'b');
const list = await gh.list(repo.full, '');
check('list: folder first, then files', JSON.stringify(list.map((x) => [x.name, x.type])) === '[["dir","dir"],["sub","dir"],["a.txt","file"],["seed.txt","file"]]');
check('list: inside a folder', (await gh.list(repo.full, 'sub')).map((x) => x.path).join() === 'app/sub/b.txt');
check('list: unseen folder is empty', (await gh.list(repo.full, 'nope')).length === 0);
await gh.remove(repo.full, 'a.txt', s1).then(() => check('remove: stale sha conflicts', false), (e) => check('remove: stale sha conflicts', e instanceof Conflict));
check('remove', (await gh.remove(repo.full, 'a.txt', s2)) === true && (await gh.read(repo.full, 'a.txt')) === null);
check('remove: already gone', (await gh.remove(repo.full, 'a.txt', s2)) === false);
check('stored under the folder', Object.keys(JSON.parse(store.get('gh-store:demo:data')).files['demo/my-data']).every((k) => k.startsWith('app/')));
const h0 = (await gh.head(repo.full)).sha;
const wm = await gh.writeMany(repo.full, { 'm1.txt': 'one', 'm2.txt': 'two', 'sub/b.txt': null }, { message: 'Batch' });
check('writeMany: all files in one commit, delete included', (await gh.read(repo.full, 'm1.txt')).text === 'one' && (await gh.read(repo.full, 'm2.txt')).text === 'two' && (await gh.read(repo.full, 'sub/b.txt')) === null && (await gh.head(repo.full)).sha === wm.commit);
await gh.writeMany(repo.full, { 'm3.txt': 'x' }, { base: h0 }).then(() => check('writeMany: base behind gives Conflict', false), (e) => check('writeMany: base behind gives Conflict', e instanceof Conflict));
const hist = await gh.history(repo.full, 'm1.txt');
check('history: the commit that made the file', hist.length === 1 && hist[0].message === 'Batch' && hist[0].sha === wm.commit);
await gh.write(repo.full, 'm1.txt', 'one v2', (await gh.read(repo.full, 'm1.txt')).sha, undefined, 'Edit m1');
const hist2 = await gh.history(repo.full, 'm1.txt');
check('history: newest first, and read(path, sha) returns that version', hist2.length === 2 && hist2[0].message === 'Edit m1' && (await gh.read(repo.full, 'm1.txt', hist2[1].sha)).text === 'one' && (await gh.read(repo.full, 'm1.txt')).text === 'one v2');
const ch = await gh.changes(repo.full, h0);
check('changes: since a commit, relative paths, net status', JSON.stringify(ch.files.map((x) => [x.path, x.status]).sort()) === JSON.stringify([['sub/b.txt', 'removed'], ['m1.txt', 'added'], ['m2.txt', 'added']].sort()));
const hd = await gh.head(repo.full);
check('head: notModified with the same etag', (await gh.head(repo.full, 'main', hd.etag)).notModified === true && (await gh.changes(repo.full, hd.sha)).files.length === 0);
const made = await gh.createRepo('fresh', { description: 'hi' });
check('createRepo: new repo appears with a README, separate from the others', made.full === 'demo-user/fresh' && (await gh.repos()).length === 2 && (await gh.list(made.full, '')).length === 1 && (await gh.read(repo.full, 'README.md')) === null);
check('createRepoFromTemplate: a new repo', (await gh.createRepoFromTemplate('tpl/x', 'viatpl')).full === 'demo-user/viatpl');
await gh.createRepo('fresh').then(() => check('createRepo: duplicate refused', false), () => check('createRepo: duplicate refused', true));
await gh.signOut();
check('signOut', !(await gh.signedIn()));
await gh.signIn();
check('signing in again keeps edits and does not reseed', (await gh.read(repo.full, 'a.txt')) === null && (await gh.read(repo.full, 'seed.txt')) !== null);
await gh.reset();
await gh.signIn();
check('reset then sign in reseeds and forgets new repos', (await gh.read(repo.full, 'seed.txt'))?.text === 'planted' && (await gh.repos()).length === 1);

console.log(fails ? `${fails} failed` : 'all passed');
process.exit(fails ? 1 : 0);
